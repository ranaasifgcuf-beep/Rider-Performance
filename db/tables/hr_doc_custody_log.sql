CREATE TABLE "HR_DOC_CUSTODY_LOG" 
   (	"LOG_ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"EMP_ID" NUMBER NOT NULL ENABLE, 
	"DOC_TYPE" VARCHAR2(30) NOT NULL ENABLE, 
	"RELATED_DOC_ID" NUMBER, 
	"TXN_TYPE" VARCHAR2(30) NOT NULL ENABLE, 
	"TXN_DT" DATE NOT NULL ENABLE, 
	"EXTERNAL_STATUS" VARCHAR2(20) NOT NULL ENABLE, 
	"HOLDER_TYPE" VARCHAR2(20) NOT NULL ENABLE, 
	"HOLDER_USER" VARCHAR2(100), 
	"HOLDER_DEPT" VARCHAR2(100), 
	"RECEIVED_FROM" VARCHAR2(200), 
	"ISSUED_TO" VARCHAR2(200), 
	"PURPOSE" VARCHAR2(500), 
	"EXPECTED_RETURN_DT" DATE, 
	"REMARKS" VARCHAR2(1000), 
	"HANDLED_BY" VARCHAR2(100) NOT NULL ENABLE, 
	"CREATED_BY" VARCHAR2(100), 
	"CREATED_DT" DATE, 
	"UPDATED_BY" VARCHAR2(100), 
	"UPDATED_DT" DATE, 
	 CHECK (txn_type in (
                           'RECEIVE_FROM_EMPLOYEE',
                           'ISSUE_TO_EMPLOYEE',
                           'INTERNAL_TRANSFER'
                         )) ENABLE, 
	 CHECK (external_status in ('WITH_COMPANY','WITH_EMPLOYEE')) ENABLE, 
	 CHECK (holder_type in ('EMPLOYEE','COMPANY_USER','COMPANY_DEPT')) ENABLE, 
	 PRIMARY KEY ("LOG_ID")
  USING INDEX  ENABLE
   ) ;
