CREATE TABLE "SEC_MODULES" 
   (	"MODULE_ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"MODULE_CODE" VARCHAR2(30) NOT NULL ENABLE, 
	"MODULE_NAME" VARCHAR2(100) NOT NULL ENABLE, 
	"ICON_CSS" VARCHAR2(100), 
	"DISPLAY_ORDER" NUMBER DEFAULT 10 NOT NULL ENABLE, 
	"IS_ACTIVE" CHAR(1) DEFAULT 'Y' NOT NULL ENABLE, 
	"CREATED_ON" DATE DEFAULT sysdate NOT NULL ENABLE, 
	"CREATED_BY" VARCHAR2(128), 
	 CHECK (is_active in ('Y','N')) ENABLE, 
	 PRIMARY KEY ("MODULE_ID")
  USING INDEX  ENABLE, 
	 UNIQUE ("MODULE_CODE")
  USING INDEX  ENABLE
   ) ;
