CREATE TABLE "SEC_USERS" 
   (	"USER_ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"USERNAME" VARCHAR2(128) NOT NULL ENABLE, 
	"EMAIL" VARCHAR2(320), 
	"FULL_NAME" VARCHAR2(200), 
	"IS_ACTIVE" CHAR(1) DEFAULT 'Y' NOT NULL ENABLE, 
	"CREATED_ON" TIMESTAMP (6) DEFAULT sysdate NOT NULL ENABLE, 
	"CREATED_BY" VARCHAR2(128), 
	"PASSWORD_HASH" VARCHAR2(4000), 
	"PASSWORD_SALT" VARCHAR2(200), 
	"PWD_CHANGED_ON" DATE, 
	"MUST_CHANGE" CHAR(1) DEFAULT 'N' NOT NULL ENABLE, 
	"LAST_LOGIN_ON" DATE, 
	"UPDATED_ON" TIMESTAMP (6), 
	"UPDATED_BY" VARCHAR2(240), 
	 CHECK (is_active in
('Y','N')) ENABLE, 
	 PRIMARY KEY ("USER_ID")
  USING INDEX  ENABLE, 
	 UNIQUE ("USERNAME")
  USING INDEX  ENABLE, 
	 CONSTRAINT "CK_SEC_USERS_MUST_CHANGE" CHECK (must_change in ('Y','N')) ENABLE
   ) ;
