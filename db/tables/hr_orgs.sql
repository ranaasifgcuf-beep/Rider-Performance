CREATE TABLE "HR_ORGS" 
   (	"ORG_ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"ORG_CODE" VARCHAR2(30) NOT NULL ENABLE, 
	"ORG_NAME" VARCHAR2(200) NOT NULL ENABLE, 
	"IS_ACTIVE" VARCHAR2(1) DEFAULT 'Y' NOT NULL ENABLE, 
	"TRADE_LIC_NO" CHAR(20), 
	"COMPANY_CODE" NUMBER, 
	"GROUP_ID" NUMBER, 
	"PARENT_ORG_ID" NUMBER, 
	"ORG_TYPE" VARCHAR2(20) DEFAULT 'COMPANY', 
	"TRADE_LIC_ISSUE_DT" DATE, 
	"TRADE_LIC_EXPIRY_DT" DATE, 
	"MOL_CODE" VARCHAR2(100), 
	"MOHRE_ESTABLISHMENT_NO" VARCHAR2(100), 
	"IMMIGRATION_FILE_NO" VARCHAR2(100), 
	"ESTABLISHMENT_CARD_NO" VARCHAR2(100), 
	"WPS_EMPLOYER_ID" VARCHAR2(100), 
	"TRN_NO" VARCHAR2(50), 
	"COUNTRY_ID" NUMBER, 
	"CITY_ID" NUMBER, 
	"ADDRESS_LINE1" VARCHAR2(250), 
	"ADDRESS_LINE2" VARCHAR2(250), 
	"PO_BOX" VARCHAR2(50), 
	"CONTACT_PERSON" VARCHAR2(120), 
	"PHONE" VARCHAR2(30), 
	"MOBILE" VARCHAR2(30), 
	"EMAIL" VARCHAR2(120), 
	"IS_MAIN_UNIT" CHAR(1) DEFAULT 'N', 
	"REMARKS" VARCHAR2(4000), 
	"CREATED_BY" VARCHAR2(100), 
	"CREATED_DT" TIMESTAMP (0) DEFAULT systimestamp, 
	"UPDATED_BY" VARCHAR2(100), 
	"UPDATED_DT" TIMESTAMP (0), 
	 PRIMARY KEY ("ORG_ID")
  USING INDEX  ENABLE, 
	 UNIQUE ("ORG_CODE")
  USING INDEX  ENABLE, 
	 CONSTRAINT "HR_ORGS_CON" UNIQUE ("ORG_NAME")
  USING INDEX  ENABLE, 
	 CONSTRAINT "CHK_HR_ORG_TYPE" CHECK (org_type in ('COMPANY','BRANCH')) ENABLE, 
	 CONSTRAINT "CHK_HR_ORG_MAIN" CHECK (is_main_unit in ('Y','N')) ENABLE, 
	 CONSTRAINT "CHK_HR_ORG_ACTIVE" CHECK (is_active in ('Y','N')) ENABLE
   ) ;
