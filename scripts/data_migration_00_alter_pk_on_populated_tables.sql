-- Run this AFTER a full expdp/impdp restore into a fresh instance,
-- BEFORE granting app access. Adds the surrogate ID + IDENTITY
-- column to the 18 tables that didn't have one, on TABLES THAT
-- ALREADY HAVE DATA (via ALTER, not CREATE) -- ADD ... GENERATED
-- BY DEFAULT AS IDENTITY on a populated table auto-backfills
-- sequential values for existing rows, this is supported since
-- Oracle 12c.
--
-- Run in the NEW instance's SQL Worksheet, Script mode.
-- ============================================================

