CREATE TABLE "HR_SIM_REQUESTS" 
   (	"REQUEST_ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"EMP_ID" NUMBER NOT NULL ENABLE, 
	"REQUEST_TYPE" VARCHAR2(50) NOT NULL ENABLE, 
	"REQUEST_STATUS" VARCHAR2(30) DEFAULT 'OPEN' NOT NULL ENABLE, 
	"PRIORITY" VARCHAR2(20) DEFAULT 'NORMAL' NOT NULL ENABLE, 
	"REQUESTED_DT" DATE, 
	"REQUESTED_BY" VARCHAR2(100), 
	"REQUIRED_BY_DT" DATE, 
	"REQUESTED_PROJECT_ID" NUMBER, 
	"REQUESTED_CITY_ID" NUMBER, 
	"CURRENT_SIM_ID" NUMBER, 
	"ASSIGNED_SIM_ID" NUMBER, 
	"SIM_ASSIGN_ID" NUMBER, 
	"REASON_CODE" VARCHAR2(50), 
	"REQUEST_REMARKS" VARCHAR2(4000), 
	"REJECTION_REASON" VARCHAR2(4000), 
	"CANCELLATION_REASON" VARCHAR2(4000), 
	"CLOSED_BY" VARCHAR2(100), 
	"CLOSED_DT" DATE, 
	"CREATED_BY" VARCHAR2(100), 
	"CREATED_DT" DATE, 
	"UPDATED_BY" VARCHAR2(100), 
	"UPDATED_DT" DATE, 
	 CONSTRAINT "CHK_SIM_REQ_TYPE" CHECK (
            request_type in (
                'NEW_ONBOARDING',
                'ADDITIONAL_SIM',
                'REPLACEMENT_LOST',
                'REPLACEMENT_DAMAGED',
                'REPLACEMENT_BLOCKED',
                'REPLACEMENT_PROJECT_CHANGE',
                'TEMPORARY_REPLACEMENT',
                'RETURN_REQUEST',
                'OTHER'
            )
        ) ENABLE, 
	 CONSTRAINT "CHK_SIM_REQ_STATUS" CHECK (
            request_status in (
                'OPEN',
                'IN_PROGRESS',
                'ASSIGNED',
                'REJECTED',
                'CANCELLED',
                'CLOSED'
            )
        ) ENABLE, 
	 CONSTRAINT "CHK_SIM_REQ_PRIORITY" CHECK (
            priority in (
                'LOW',
                'NORMAL',
                'HIGH',
                'URGENT'
            )
        ) ENABLE, 
	 PRIMARY KEY ("REQUEST_ID")
  USING INDEX  ENABLE
   ) ;
