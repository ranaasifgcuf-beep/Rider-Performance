CREATE TABLE "HR_APPROVAL_RULE_STEPS" 
   (	"RULE_STEP_ID" NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"RULE_ID" NUMBER NOT NULL ENABLE, 
	"STEP_SEQ" NUMBER NOT NULL ENABLE, 
	"STEP_NAME" VARCHAR2(150), 
	"APPROVER_TYPE" VARCHAR2(30) NOT NULL ENABLE, 
	"APPROVER_USER_NAME" VARCHAR2(100), 
	"APPROVER_ROLE_CODE" VARCHAR2(100), 
	"CREATED_BY" VARCHAR2(100), 
	"CREATED_DT" TIMESTAMP (0), 
	"UPDATED_BY" VARCHAR2(100), 
	"UPDATED_DT" TIMESTAMP (0), 
	 CHECK (approver_type in ('USER','ROLE')) ENABLE, 
	 CONSTRAINT "CHK_APPR_STEP_USER_ROLE" CHECK (
        (approver_type = 'USER' and approver_user_name is not null and approver_role_code is null)
        or
        (approver_type = 'ROLE' and approver_role_code is not null and approver_user_name is null)
    ) ENABLE, 
	 PRIMARY KEY ("RULE_STEP_ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UK_APPR_RULE_STEP" UNIQUE ("RULE_ID", "STEP_SEQ")
  USING INDEX  ENABLE
   ) ;
