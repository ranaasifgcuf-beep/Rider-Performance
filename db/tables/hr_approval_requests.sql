CREATE TABLE "HR_APPROVAL_REQUESTS" 
   (	"APPROVAL_ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"MODULE_CODE" VARCHAR2(50) NOT NULL ENABLE, 
	"RECORD_PK" NUMBER NOT NULL ENABLE, 
	"TXN_TYPE_CODE" VARCHAR2(50), 
	"ORG_ID" NUMBER, 
	"APPROVAL_SUBJECT" VARCHAR2(300) NOT NULL ENABLE, 
	"APPROVAL_AMOUNT" NUMBER(12,2), 
	"RULE_ID" NUMBER, 
	"WORKFLOW_ID" NUMBER, 
	"REQUEST_STATUS" VARCHAR2(30) DEFAULT 'DRAFT' NOT NULL ENABLE, 
	"REQUESTED_BY" VARCHAR2(100), 
	"REQUESTED_DT" TIMESTAMP (0), 
	"FINAL_ACTION_DONE" CHAR(1) DEFAULT 'N' NOT NULL ENABLE, 
	"CREATED_BY" VARCHAR2(100), 
	"CREATED_DT" TIMESTAMP (0), 
	"UPDATED_BY" VARCHAR2(100), 
	"UPDATED_DT" TIMESTAMP (0), 
	 CHECK (request_status in ('DRAFT','SUBMITTED','APPROVED','REJECTED','CANCELLED','ERROR')) ENABLE, 
	 CHECK (final_action_done in ('Y','N')) ENABLE, 
	 PRIMARY KEY ("APPROVAL_ID")
  USING INDEX  ENABLE
   ) ;
