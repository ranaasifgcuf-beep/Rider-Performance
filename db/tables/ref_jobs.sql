CREATE TABLE "REF_JOBS" 
   (	"JOB_ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"JOB_NAME" VARCHAR2(100) NOT NULL ENABLE, 
	"IS_OFFICE_STAFF" CHAR(1) DEFAULT 'N' NOT NULL ENABLE, 
	"REQUIRES_LICENSE" CHAR(1) DEFAULT 'Y' NOT NULL ENABLE, 
	"IS_ACTIVE" CHAR(1) DEFAULT 'Y' NOT NULL ENABLE, 
	"BIKE_REQUIRED_YN" CHAR(1) DEFAULT 'N' NOT NULL ENABLE, 
	 CHECK (is_office_staff in ('Y','N')) ENABLE, 
	 CHECK (requires_license in ('Y','N')) ENABLE, 
	 CHECK (is_active in ('Y','N')) ENABLE, 
	 PRIMARY KEY ("JOB_ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "CHK_REF_JOBS_BIKE_REQUIRED" CHECK (bike_required_yn in ('Y','N')) ENABLE
   ) ;
