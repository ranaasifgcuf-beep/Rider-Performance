CREATE TABLE "HR_EMP_DOCS" 
   (	"DOC_ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"EMP_ID" NUMBER NOT NULL ENABLE, 
	"DOC_TYPE" VARCHAR2(40) NOT NULL ENABLE, 
	"DOC_NO" VARCHAR2(60), 
	"ISSUE_DT" DATE, 
	"EXPIRY_DT" DATE, 
	"IS_CURRENT_RECORD" CHAR(1) DEFAULT 'Y' NOT NULL ENABLE, 
	"RELATED_ID_REC_ID" NUMBER, 
	"FILE_REF" VARCHAR2(4000), 
	"REMARKS" VARCHAR2(4000), 
	"CREATED_BY" VARCHAR2(100) DEFAULT coalesce(sys_context('APEX$SESSION','APP_USER'), user) NOT NULL ENABLE, 
	"CREATED_DT" TIMESTAMP (0) DEFAULT systimestamp NOT NULL ENABLE, 
	"UPDATED_BY" VARCHAR2(100), 
	"UPDATED_DT" TIMESTAMP (0), 
	"FILE_NAME" VARCHAR2(500), 
	"MIME_TYPE" VARCHAR2(255), 
	"FILE_BLOB" BLOB, 
	"FILE_SIZE" NUMBER, 
	 CHECK (is_current_record in ('Y','N')) ENABLE, 
	 PRIMARY KEY ("DOC_ID")
  USING INDEX  ENABLE
   ) ;
