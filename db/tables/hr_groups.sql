CREATE TABLE "HR_GROUPS" 
   (	"GROUP_ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"GROUP_CODE" VARCHAR2(30) NOT NULL ENABLE, 
	"GROUP_NAME" VARCHAR2(200) NOT NULL ENABLE, 
	"OWNER_NAME" VARCHAR2(200), 
	"IS_ACTIVE" CHAR(1) DEFAULT 'Y' NOT NULL ENABLE, 
	"REMARKS" VARCHAR2(4000), 
	"CREATED_BY" VARCHAR2(100) DEFAULT coalesce(sys_context('APEX$SESSION','APP_USER'), user) NOT NULL ENABLE, 
	"CREATED_DT" TIMESTAMP (0) DEFAULT systimestamp NOT NULL ENABLE, 
	"UPDATED_BY" VARCHAR2(100), 
	"UPDATED_DT" TIMESTAMP (0), 
	 CHECK (is_active in ('Y','N')) ENABLE, 
	 PRIMARY KEY ("GROUP_ID")
  USING INDEX  ENABLE
   ) ;
