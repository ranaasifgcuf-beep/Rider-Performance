CREATE TABLE "FLEET_BIKE_ACCIDENTS" 
   (	"ACCIDENT_ID" NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"BIKE_ID" NUMBER NOT NULL ENABLE, 
	"EMP_ID" NUMBER, 
	"ACCIDENT_DT" DATE NOT NULL ENABLE, 
	"ACCIDENT_LOCATION" VARCHAR2(200), 
	"POLICE_REPORT_NO" VARCHAR2(100), 
	"FAULT_TYPE" VARCHAR2(20), 
	"ACCIDENT_SEVERITY" VARCHAR2(20), 
	"REPAIR_START_DT" DATE, 
	"REPAIR_END_DT" DATE, 
	"ESTIMATED_COST" NUMBER(12,2), 
	"ACTUAL_COST" NUMBER(12,2), 
	"CHARGE_TO_EMPLOYEE_YN" VARCHAR2(1) DEFAULT 'N', 
	"EXCLUDED_FROM_CHARGE_YN" VARCHAR2(1) DEFAULT 'N', 
	"EMP_CHARGE_ID" NUMBER, 
	"STATUS_CODE" VARCHAR2(20) DEFAULT 'OPEN', 
	"REMARKS" VARCHAR2(500), 
	"CREATED_BY" VARCHAR2(100), 
	"CREATED_DT" DATE, 
	"UPDATED_BY" VARCHAR2(100), 
	"UPDATED_DT" DATE, 
	 CONSTRAINT "CK_FAULT_TYPE" CHECK (fault_type in ('EMPLOYEE','COMPANY','THIRD_PARTY')) ENABLE, 
	 CONSTRAINT "CK_STATUS" CHECK (status_code in ('OPEN','UNDER_REPAIR','CLOSED')) ENABLE, 
	 CONSTRAINT "CK_DATES" CHECK (
            repair_start_dt is null or repair_start_dt >= accident_dt
        ) ENABLE, 
	 CONSTRAINT "FLEET_BIKE_ACCIDENTS_PK" PRIMARY KEY ("ACCIDENT_ID")
