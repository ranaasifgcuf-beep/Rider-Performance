CREATE TABLE "HR_EMP_LOAN_TXNS" 
   (	"LOAN_TXN_ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"LOAN_ID" NUMBER NOT NULL ENABLE, 
	"EMP_ID" NUMBER NOT NULL ENABLE, 
	"TXN_DATE" DATE DEFAULT trunc(cast(systimestamp at time zone 'Asia/Dubai' as date)) NOT NULL ENABLE, 
	"PAYROLL_MONTH" DATE, 
	"TXN_TYPE" VARCHAR2(30) NOT NULL ENABLE, 
	"AMOUNT" NUMBER(12,2) NOT NULL ENABLE, 
	"PAY_MODE" VARCHAR2(30), 
	"REFERENCE_NO" VARCHAR2(100), 
	"SOURCE_TYPE" VARCHAR2(40), 
	"SOURCE_ID" NUMBER, 
	"REMARKS" VARCHAR2(4000), 
	"REVERSAL_OF_TXN_ID" NUMBER, 
	"CREATED_BY" VARCHAR2(100), 
	"CREATED_DT" TIMESTAMP (0), 
	"UPDATED_BY" VARCHAR2(100), 
	"UPDATED_DT" TIMESTAMP (0), 
	"APPROVAL_STATUS" VARCHAR2(20) DEFAULT 'APPROVED' NOT NULL ENABLE, 
	"APPROVAL_ID" NUMBER, 
	"APPROVED_BY" VARCHAR2(100), 
	"APPROVED_DT" TIMESTAMP (0), 
	"REJECTED_BY" VARCHAR2(100), 
	"REJECTED_DT" TIMESTAMP (0), 
	"REJECTION_REASON" VARCHAR2(4000), 
	 PRIMARY KEY ("LOAN_TXN_ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "CK_LOAN_TXN_APPR_STATUS" CHECK (approval_status in ('DRAFT','SUBMITTED','APPROVED','REJECTED','CANCELLED')) ENABLE, 
	 CONSTRAINT "CK_LOAN_TXN_TYPE" CHECK (txn_type in (
    'PAYROLL_DEDUCTION',
    'MANUAL_PAYMENT',
    'WAIVER',
    'ADJUSTMENT',
    'REVERSAL',
    'BAD_DEBT_WRITE_OFF'
)) ENABLE
   ) ;
