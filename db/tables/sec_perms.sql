CREATE TABLE "SEC_PERMS" 
   (	"PERM_ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"PERM_CODE" VARCHAR2(80) NOT NULL ENABLE, 
	"PERM_NAME" VARCHAR2(200) NOT NULL ENABLE, 
	"MODULE_ID" NUMBER NOT NULL ENABLE, 
	"IS_ACTIVE" CHAR(1) DEFAULT 'Y' NOT NULL ENABLE, 
	 CHECK (is_active in ('Y','N')) ENABLE, 
	 PRIMARY KEY ("PERM_ID")
  USING INDEX  ENABLE, 
	 UNIQUE ("PERM_CODE")
  USING INDEX  ENABLE
   ) ;
