CREATE TABLE "FLEET_SIMS" 
   (	"SIM_ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"MOBILE_NO" VARCHAR2(30) NOT NULL ENABLE, 
	"ICCID_NO" VARCHAR2(100), 
	"OPERATOR_CODE" VARCHAR2(30) NOT NULL ENABLE, 
	"SIM_STATUS_CODE" VARCHAR2(30) DEFAULT 'AVAILABLE' NOT NULL ENABLE, 
	"OWNERSHIP_TYPE" VARCHAR2(30) DEFAULT 'COMPANY' NOT NULL ENABLE, 
	"OWNER_SUPPLIER_ID" NUMBER, 
	"EXTERNAL_OWNER_NAME" VARCHAR2(200), 
	"EXTERNAL_OWNER_MOBILE" VARCHAR2(50), 
	"EXTERNAL_OWNER_REF" VARCHAR2(100), 
	"PLAN_NAME" VARCHAR2(100), 
	"DATA_PACKAGE" VARCHAR2(100), 
	"MONTHLY_COST" NUMBER(12,2), 
	"BILL_ACCOUNT_NO" VARCHAR2(100), 
	"CONTRACT_NO" VARCHAR2(100), 
	"BILLING_REMARKS" VARCHAR2(1000), 
	"ACTIVATION_DT" DATE, 
	"CANCELLATION_DT" DATE, 
	"REMARKS" VARCHAR2(4000), 
	"CREATED_BY" VARCHAR2(100), 
	"CREATED_DT" DATE, 
	"UPDATED_BY" VARCHAR2(100), 
	"UPDATED_DT" DATE, 
	 CONSTRAINT "CHK_FLEET_SIMS_OWNER" CHECK (
            ownership_type in (
                'COMPANY',
                'SUPPLIER',
                'EMPLOYEE',
                'CLIENT',
                'THIRD_PARTY',
                'RENTAL',
                'OTHER'
            )
        ) ENABLE, 
	 CONSTRAINT "CHK_FLEET_SIMS_SUPPLIER_OWNER" CHECK (
            ownership_type <> 'SUPPLIER'
            or owner_supplier_id is not null
        ) ENABLE, 
	 CONSTRAINT "CHK_FLEET_SIMS_EXTERNAL_OWNER" CHECK (
            ownership_type not in ('CLIENT','THIRD_PARTY','OTHER')
            or external_owner_name is not null
        ) ENABLE, 
	 PRIMARY KEY ("SIM_ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UK_FLEET_SIMS_MOBILE" UNIQUE ("MOBILE_NO")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UK_FLEET_SIMS_ICCID" UNIQUE ("ICCID_NO")
  USING INDEX  ENABLE, 
	 CONSTRAINT "CHK_FLEET_SIMS_RENTAL_OWNER" CHECK (
       ownership_type  IN ('RENTAL', 'EMPLOYEE')
       OR owner_supplier_id IS NOT NULL
       OR external_owner_name IS NOT NULL
) ENABLE
   ) ;
