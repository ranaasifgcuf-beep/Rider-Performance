CREATE TABLE "HR_EMP_INSURANCE" 
   (	"INSURANCE_ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"EMP_ID" NUMBER NOT NULL ENABLE, 
	"INSURANCE_TYPE" VARCHAR2(20) NOT NULL ENABLE, 
	"PROVIDER_NAME" VARCHAR2(200) NOT NULL ENABLE, 
	"POLICY_NO" VARCHAR2(100), 
	"MEMBER_CARD_NO" VARCHAR2(100), 
	"PLAN_NAME" VARCHAR2(200), 
	"CLASS_NAME" VARCHAR2(100), 
	"ISSUE_DT" DATE, 
	"START_DT" DATE NOT NULL ENABLE, 
	"EXPIRY_DT" DATE, 
	"NEAR_EXPIRY_DAYS" NUMBER DEFAULT 30 NOT NULL ENABLE, 
	"STATUS_CODE" VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL ENABLE, 
	"IS_CURRENT" CHAR(1) DEFAULT 'Y' NOT NULL ENABLE, 
	"CANCEL_DT" DATE, 
	"CANCEL_REASON" VARCHAR2(1000), 
	"CANCELLED_BY" VARCHAR2(100), 
	"REMARKS" VARCHAR2(1000), 
	"CREATED_BY" VARCHAR2(100), 
	"CREATED_DT" DATE, 
	"UPDATED_BY" VARCHAR2(100), 
	"UPDATED_DT" DATE, 
	 CHECK (insurance_type in ('HEALTH','WC')) ENABLE, 
	 CHECK (status_code in ('ACTIVE','EXPIRED','CANCELLED')) ENABLE, 
	 CHECK (is_current in ('Y','N')) ENABLE, 
	 PRIMARY KEY ("INSURANCE_ID")
  USING INDEX  ENABLE
   ) ;
