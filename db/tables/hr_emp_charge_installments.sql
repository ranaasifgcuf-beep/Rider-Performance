CREATE TABLE "HR_EMP_CHARGE_INSTALLMENTS" 
   (	"INSTALLMENT_ID" NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"EMP_CHARGE_ID" NUMBER NOT NULL ENABLE, 
	"INSTALLMENT_NO" NUMBER NOT NULL ENABLE, 
	"DUE_DT" DATE NOT NULL ENABLE, 
	"AMOUNT" NUMBER(12,2) NOT NULL ENABLE, 
	"STATUS_CODE" VARCHAR2(20) DEFAULT 'PENDING' NOT NULL ENABLE, 
	"HOLD_FROM_DT" DATE, 
	"HOLD_TO_DT" DATE, 
	"PAYROLL_RUN_REF" VARCHAR2(100), 
	"PROCESSED_TS" TIMESTAMP (6), 
	"REMARKS" VARCHAR2(500), 
	"CREATED_BY" VARCHAR2(100), 
	"CREATED_DT" DATE, 
	"UPDATED_BY" VARCHAR2(100), 
	"UPDATED_DT" DATE, 
	 CONSTRAINT "HR_EMP_CHARGE_INSTALLMENTS_CK2" CHECK (
        amount > 0
    ) ENABLE, 
	 CONSTRAINT "HR_EMP_CHARGE_INSTALLMENTS_CK3" CHECK (
        hold_to_dt is null
        or hold_from_dt is null
        or hold_to_dt >= hold_from_dt
    ) ENABLE, 
	 CONSTRAINT "HR_EMP_CHARGE_INSTALLMENTS_PK" PRIMARY KEY ("INSTALLMENT_ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "HR_EMP_CHARGE_INSTALLMENTS_UK1" UNIQUE ("EMP_CHARGE_ID", "INSTALLMENT_NO")
  USING INDEX  ENABLE
   ) ;
