CREATE TABLE "HR_ORG_DOCS" 
   (	"ORG_DOC_ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"ORG_ID" NUMBER NOT NULL ENABLE, 
	"DOC_TYPE_CODE" VARCHAR2(40) NOT NULL ENABLE, 
	"DOC_NO" VARCHAR2(100), 
	"ISSUE_DT" DATE, 
	"EXPIRY_DT" DATE, 
	"IS_CURRENT" CHAR(1) DEFAULT 'Y' NOT NULL ENABLE, 
	"IS_ACTIVE" CHAR(1) DEFAULT 'Y' NOT NULL ENABLE, 
	"FILE_REF" VARCHAR2(4000), 
	"REMARKS" VARCHAR2(4000), 
	"CREATED_BY" VARCHAR2(100) DEFAULT coalesce(sys_context('APEX$SESSION','APP_USER'), user) NOT NULL ENABLE, 
	"CREATED_DT" TIMESTAMP (0) DEFAULT systimestamp NOT NULL ENABLE, 
	"UPDATED_BY" VARCHAR2(100), 
	"UPDATED_DT" TIMESTAMP (0), 
	 CHECK (is_current in ('Y','N')) ENABLE, 
	 CHECK (is_active in ('Y','N')) ENABLE, 
	 PRIMARY KEY ("ORG_DOC_ID")
  USING INDEX  ENABLE
   ) ;
