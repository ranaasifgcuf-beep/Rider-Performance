CREATE TABLE "FLEET_BIKES" 
   (	"BIKE_ID" NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"BIKE_CODE" VARCHAR2(30) NOT NULL ENABLE, 
	"PLATE_NO" VARCHAR2(30) NOT NULL ENABLE, 
	"PLATE_EMIRATE" VARCHAR2(30) NOT NULL ENABLE, 
	"CHASSIS_NO" VARCHAR2(100), 
	"ENGINE_NO" VARCHAR2(100), 
	"MODEL_ID" NUMBER, 
	"MODEL_YEAR" NUMBER(4,0), 
	"COLOR_ID" NUMBER, 
	"OWNERSHIP_TYPE" VARCHAR2(20) NOT NULL ENABLE, 
	"VENDOR_ID" NUMBER, 
	"PURCHASE_DT" DATE, 
	"PURCHASE_AMOUNT" NUMBER(12,2), 
	"CURRENT_MONTHLY_RENT" NUMBER(12,2), 
	"CONTRACT_START_DT" DATE, 
	"CONTRACT_END_DT" DATE, 
	"REMARKS" VARCHAR2(500), 
	"IS_ACTIVE" VARCHAR2(1) DEFAULT 'Y' NOT NULL ENABLE, 
	"CREATED_BY" VARCHAR2(100), 
	"CREATED_DT" DATE, 
	"UPDATED_BY" VARCHAR2(100), 
	"UPDATED_DT" DATE, 
	 CONSTRAINT "FLEET_BIKES_CK1" CHECK (ownership_type in ('COMPANY','RENTAL')) ENABLE, 
	 CONSTRAINT "FLEET_BIKES_CK2" CHECK (is_active in ('Y','N')) ENABLE, 
	 CONSTRAINT "FLEET_BIKES_CK3" CHECK (
            contract_end_dt is null
            or contract_start_dt is null
            or contract_end_dt >= contract_start_dt
        ) ENABLE, 
	 CONSTRAINT "FLEET_BIKES_PK" PRIMARY KEY ("BIKE_ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "FLEET_BIKES_UK1" UNIQUE ("BIKE_CODE")
  USING INDEX  ENABLE, 
	 CONSTRAINT "FLEET_BIKES_UK2" UNIQUE ("PLATE_NO")
  USING INDEX  ENABLE
   ) ;
