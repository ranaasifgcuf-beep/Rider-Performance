CREATE TABLE "HR_PRO_DEALS" 
   (	"DEAL_ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"DEAL_NO" VARCHAR2(50) NOT NULL ENABLE, 
	"EMP_ID" NUMBER NOT NULL ENABLE, 
	"ORG_ID" NUMBER, 
	"DEAL_TYPE_CODE" VARCHAR2(40) NOT NULL ENABLE, 
	"ENTRY_STATUS" VARCHAR2(30), 
	"DEAL_ADVANCE" NUMBER(12,2), 
	"DEAL_AMOUNT" NUMBER(12,2) NOT NULL ENABLE, 
	"RECOVERABLE" CHAR(1) DEFAULT 'Y' NOT NULL ENABLE, 
	"EMI_AMOUNT" NUMBER(12,2), 
	"RECOVERY_START_MONTH" DATE, 
	"AGREEMENT_REQUIRED" CHAR(1) DEFAULT 'Y' NOT NULL ENABLE, 
	"AGREEMENT_PRINTED" CHAR(1) DEFAULT 'N' NOT NULL ENABLE, 
	"AGREEMENT_SIGNED" CHAR(1) DEFAULT 'N' NOT NULL ENABLE, 
	"APPROVAL_STATUS" VARCHAR2(30) DEFAULT 'DRAFT' NOT NULL ENABLE, 
	"SUBMITTED_BY" VARCHAR2(100), 
	"SUBMITTED_DT" TIMESTAMP (0), 
	"APPROVED_BY" VARCHAR2(100), 
	"APPROVED_DT" TIMESTAMP (0), 
	"REJECTED_BY" VARCHAR2(100), 
	"REJECTED_DT" TIMESTAMP (0), 
	"REJECTION_REASON" VARCHAR2(4000), 
	"LOAN_CREATED" CHAR(1) DEFAULT 'N' NOT NULL ENABLE, 
	"LOAN_ID" NUMBER, 
	"PRO_CASE_CREATED" CHAR(1) DEFAULT 'N' NOT NULL ENABLE, 
	"PRO_CASE_ID" NUMBER, 
	"REMARKS" VARCHAR2(4000), 
	"CREATED_BY" VARCHAR2(100), 
	"CREATED_DT" TIMESTAMP (0), 
	"UPDATED_BY" VARCHAR2(100), 
	"UPDATED_DT" TIMESTAMP (0), 
	 CHECK (recoverable in ('Y','N')) ENABLE, 
	 CHECK (agreement_required in ('Y','N')) ENABLE, 
	 CHECK (agreement_printed in ('Y','N')) ENABLE, 
	 CHECK (agreement_signed in ('Y','N')) ENABLE, 
	 CHECK (approval_status in ('DRAFT','SUBMITTED','APPROVED','REJECTED','CANCELLED')) ENABLE, 
	 CHECK (loan_created in ('Y','N')) ENABLE, 
	 CHECK (pro_case_created in ('Y','N')) ENABLE, 
	 CONSTRAINT "CHK_PRO_DEAL_AMOUNT" CHECK (deal_amount >= 0) ENABLE, 
	 CONSTRAINT "CHK_PRO_DEAL_EMI" CHECK (emi_amount is null or emi_amount >= 0) ENABLE, 
	 PRIMARY KEY ("DEAL_ID")
  USING INDEX  ENABLE
   ) ;
