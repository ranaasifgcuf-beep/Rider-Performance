CREATE TABLE "HR_PROJECTS" 
   (	"PROJECT_ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"PROJECT_CODE" VARCHAR2(30) NOT NULL ENABLE, 
	"PROJECT_NAME" VARCHAR2(200) NOT NULL ENABLE, 
	"IS_ACTIVE" VARCHAR2(1), 
	 PRIMARY KEY ("PROJECT_ID")
  USING INDEX  ENABLE, 
	 UNIQUE ("PROJECT_CODE")
  USING INDEX  ENABLE, 
	 CONSTRAINT "HR_PROJECTS_CON" UNIQUE ("PROJECT_NAME")
  USING INDEX  ENABLE
   ) ;
