CREATE TABLE "SEC_AUDIT_LOG" 
   (	"AUDIT_ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"MODULE" VARCHAR2(30), 
	"ACTION" VARCHAR2(50), 
	"RECORD_KEY" VARCHAR2(200), 
	"DETAILS" CLOB, 
	"CHANGED_BY" VARCHAR2(128), 
	"CHANGED_ON" TIMESTAMP (6) DEFAULT systimestamp NOT NULL ENABLE, 
	 PRIMARY KEY ("AUDIT_ID")
  USING INDEX  ENABLE
   ) ;
