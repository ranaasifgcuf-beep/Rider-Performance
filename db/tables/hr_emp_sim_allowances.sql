CREATE TABLE "HR_EMP_SIM_ALLOWANCES" 
   (	"ALLOWANCE_ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"EMP_ID" NUMBER NOT NULL ENABLE, 
	"MAX_ACTIVE_SIMS" NUMBER DEFAULT 1 NOT NULL ENABLE, 
	"EFFECTIVE_FROM" DATE DEFAULT trunc(sysdate) NOT NULL ENABLE, 
	"EFFECTIVE_TO" DATE, 
	"APPROVAL_REF" VARCHAR2(100), 
	"APPROVED_BY" VARCHAR2(100), 
	"APPROVED_DT" DATE, 
	"REASON" VARCHAR2(4000), 
	"IS_ACTIVE" CHAR(1) DEFAULT 'Y' NOT NULL ENABLE, 
	"CREATED_BY" VARCHAR2(100), 
	"CREATED_DT" DATE, 
	"UPDATED_BY" VARCHAR2(100), 
	"UPDATED_DT" DATE, 
	 CONSTRAINT "CHK_EMP_SIM_ALLOW_ACTIVE" CHECK (is_active in ('Y','N')) ENABLE, 
	 CONSTRAINT "CHK_EMP_SIM_ALLOW_MAX" CHECK (max_active_sims between 1 and 5) ENABLE, 
	 CONSTRAINT "CHK_EMP_SIM_ALLOW_DATES" CHECK (effective_to is null or effective_to >= effective_from) ENABLE, 
	 PRIMARY KEY ("ALLOWANCE_ID")
