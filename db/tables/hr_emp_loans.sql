CREATE TABLE "HR_EMP_LOANS" 
   (	"LOAN_ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"LOAN_NO" VARCHAR2(50) NOT NULL ENABLE, 
	"EMP_ID" NUMBER NOT NULL ENABLE, 
	"LOAN_TYPE" VARCHAR2(40) NOT NULL ENABLE, 
	"LOAN_AMOUNT" NUMBER(12,2) NOT NULL ENABLE, 
	"EMI_AMOUNT" NUMBER(12,2), 
	"ISSUE_DT" DATE DEFAULT trunc(sysdate) NOT NULL ENABLE, 
	"START_MONTH" DATE, 
	"SOURCE_TYPE" VARCHAR2(40), 
	"SOURCE_ID" NUMBER, 
	"APPROVAL_STATUS" VARCHAR2(20) DEFAULT 'APPROVED' NOT NULL ENABLE, 
	"STATUS" VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL ENABLE, 
	"REMARKS" VARCHAR2(4000), 
	"CREATED_BY" VARCHAR2(100), 
	"CREATED_DT" TIMESTAMP (0), 
	"UPDATED_BY" VARCHAR2(100), 
	"UPDATED_DT" TIMESTAMP (0), 
	"APPROVED_BY" VARCHAR2(100), 
	"APPROVED_DT" TIMESTAMP (6), 
	"REJECTION_REASON" VARCHAR2(4000), 
	"AGREED_ADVANCE_AMOUNT" NUMBER DEFAULT 0 NOT NULL ENABLE, 
	 CHECK (approval_status in ('DRAFT','APPROVED','REJECTED','CANCELLED')) DISABLE, 
	 CHECK (status in ('ACTIVE','COMPLETED','CANCELLED')) ENABLE, 
	 PRIMARY KEY ("LOAN_ID")
  USING INDEX  ENABLE
   ) ;
