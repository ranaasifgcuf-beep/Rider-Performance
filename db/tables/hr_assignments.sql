CREATE TABLE "HR_ASSIGNMENTS" 
   (	"ASG_ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"EMP_ID" NUMBER NOT NULL ENABLE, 
	"PROJECT_ID" NUMBER NOT NULL ENABLE, 
	"CITY_ID" NUMBER NOT NULL ENABLE, 
	"SUPERVISOR_EMP_ID" NUMBER, 
	"START_DT" DATE NOT NULL ENABLE, 
	"END_DT" DATE, 
	"STATUS" VARCHAR2(15) DEFAULT 'ACTIVE' NOT NULL ENABLE, 
	"CREATED_BY" VARCHAR2(100) DEFAULT coalesce(sys_context('APEX$SESSION','APP_USER'), user) NOT NULL ENABLE, 
	"CREATED_DT" TIMESTAMP (0) DEFAULT systimestamp NOT NULL ENABLE, 
	"UPDATED_BY" VARCHAR2(240), 
	"UPDATED_DT" TIMESTAMP (6), 
	"REMARKS" VARCHAR2(240), 
	"AGG_RIDER_ID" VARCHAR2(240), 
	"JOB_ID" NUMBER, 
	 CHECK (status in ('ACTIVE','ENDED')) ENABLE, 
	 PRIMARY KEY ("ASG_ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "HR_ASSIGNMENTS_CON" CHECK ( "JOB_ID" is not null ) ENABLE
   ) ;
