CREATE TABLE "HR_STATUS_MASTER" 
   (	"STATUS_CODE" VARCHAR2(30), 
	"STATUS_NAME" VARCHAR2(100) NOT NULL ENABLE, 
	"IS_ACTIVE" CHAR(1) DEFAULT 'Y' NOT NULL ENABLE, 
	"SEQ_NO" NUMBER, 
	"REMARKS" VARCHAR2(4000), 
	"STATUS_TYPE" VARCHAR2(20) DEFAULT 'USER', 
	"USER_CHANGEABLE" CHAR(1) DEFAULT 'Y', 
	"STATUS_NATURE" VARCHAR2(240), 
	"REQUIRES_REASON_YN" CHAR(1) DEFAULT 'N' NOT NULL ENABLE, 
	"REQUIRES_PROJECT_YN" CHAR(1) DEFAULT 'N' NOT NULL ENABLE, 
	"REQUIRES_CITY_YN" CHAR(1) DEFAULT 'N' NOT NULL ENABLE, 
	"ALLOW_ASSIGNMENT_YN" CHAR(1) DEFAULT 'N' NOT NULL ENABLE, 
	"IS_FINAL_YN" CHAR(1) DEFAULT 'N' NOT NULL ENABLE, 
	"BADGE_CLASS" VARCHAR2(100), 
	 CHECK (is_active in ('Y','N')) ENABLE, 
	 PRIMARY KEY ("STATUS_CODE")
  USING INDEX  ENABLE, 
	 CHECK (status_type in ('SYSTEM','USER')) ENABLE, 
	 CHECK (user_changeable in ('Y','N')) ENABLE, 
	 CONSTRAINT "CHK_HR_SM_REQ_REASON" CHECK (requires_reason_yn in ('Y','N')) ENABLE, 
	 CONSTRAINT "CHK_HR_SM_REQ_PROJECT" CHECK (requires_project_yn in ('Y','N')) ENABLE, 
	 CONSTRAINT "CHK_HR_SM_REQ_CITY" CHECK (requires_city_yn in ('Y','N')) ENABLE, 
	 CONSTRAINT "CHK_HR_SM_ALLOW_ASG" CHECK (allow_assignment_yn in ('Y','N')) ENABLE
   ) ;
