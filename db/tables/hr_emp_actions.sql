CREATE TABLE "HR_EMP_ACTIONS" 
   (	"ACTION_ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"EMP_ID" NUMBER NOT NULL ENABLE, 
	"ACTION_TYPE" VARCHAR2(30) NOT NULL ENABLE, 
	"TARGET_STATUS" VARCHAR2(30) NOT NULL ENABLE, 
	"ACTION_DT" DATE DEFAULT trunc(sysdate) NOT NULL ENABLE, 
	"AMOUNT" NUMBER, 
	"REMARKS" VARCHAR2(4000), 
	"ATTACHMENT_REF" VARCHAR2(4000), 
	"STATUS" VARCHAR2(20) DEFAULT 'DONE' NOT NULL ENABLE, 
	"CREATED_BY" VARCHAR2(100) DEFAULT coalesce(sys_context('APEX$SESSION','APP_USER'), user) NOT NULL ENABLE, 
	"CREATED_DT" TIMESTAMP (0) DEFAULT systimestamp NOT NULL ENABLE, 
	 CHECK (status in ('DRAFT','DONE','CANCELLED')) ENABLE, 
	 PRIMARY KEY ("ACTION_ID")
  USING INDEX  ENABLE
   ) ;
